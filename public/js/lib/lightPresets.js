export const LIGHT_PRESET_BASES = LIGHT_PRESET_DEFAULTS;

export function cloneLightPresetDefaults() {
  return Object.fromEntries(
    Object.entries(LIGHT_PRESET_DEFAULTS).map(([name, preset]) => [
      name,
      {
        ...preset,
        layerTints: Array.isArray(preset.layerTints) ? preset.layerTints.slice() : []
      }
    ])
  );
}

export function getVillageLightPresetNameForSky(name) {
  if (name === 'night') return 'night';
  if (name === 'fullsun' || name === 'day') return 'day';
  return 'sunset';
}

export function getVillageLightPresetForSky(name) {
  return LIGHT_PRESET_DEFAULTS[getVillageLightPresetNameForSky(name)];
}
